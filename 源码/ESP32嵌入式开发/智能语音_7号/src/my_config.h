// ================ 固定的配置（所有设备都相同） ================
// 【注意】这里叫 WIFI_SSID / WIFI_PASSWORD，不叫协议附录 A 里写的
// SSID / PASSWORD。原因是宏名会全局替换：ESP32 的 WiFi.h 里有一个
// 方法就叫 SSID()，一旦 #define SSID "..."，那行声明会被替换成
//     String "IOT-SZCS01"() const;
// 直接编译报错 "expected unqualified-id before string constant"。
// 课堂例程没踩到，是因为它把 #include <WiFi.h> 写在了
// #include "my_config.h" 前面；而本工程的 mqtt_proto.h 是先包含
// my_config.h 的，所以必须改名，不能靠包含顺序。
#define WIFI_SSID     "wusuijie"        // WiFi账号
#define WIFI_PASSWORD "11111111"        // WiFi密码
#define MQTT_SERVER   "yunyismart.tech" // MQTT服务器地址
#define MQTT_PORT     1883              // MQTT服务器端口号

// ================ 本组编号与主题定义 ================
// 前缀 = 课程空间前缀 202609_PP2 + 组号 1
#define GROUP_ID 1
#define TOPIC_CMD "202609_PP2/1/cmd"       // 下行：各平台 → 各板
#define TOPIC_REPORT "202609_PP2/1/report" // 上行：各板 → 各平台（本板旁听）
#define TOPIC_ONLINE "202609_PP2/1/online" // 上行：上线下线，Retain（本板旁听）

// ================ 本设备板号（1~8，按协议表 7） ================
#define BOARD_ID 7
#define BOARD_ID_STR "7"

// ================ 设备标识（协议表 7） ================
#define DEV_TTS "tts"

// ================ 语音模块的串口（UART2） ================
// ESP32 的 GPIO17 接模块 RXD，GPIO16 接模块 TXD（课堂例程的接法）。
// 若实际接线不同，只改这两行。
#define TTS_RX_PIN 16
#define TTS_TX_PIN 17

// 115200，8 位数据，偶校验，1 位停止位。
// 【注意】波特率和校验位写错的现象都是「完全没声音」，而且不报任何错，
//         是最难查的一类故障，这两个值别随手改。
#define TTS_BAUD 115200

// ================ 播报文本限制 ================
// 语音模块缓冲区有限，协议 §5.7 建议播报文本不超过 100 字节。
// 这里说的是【GB2312 编码后的字节数】，一个汉字算 2 字节。
#define TTS_MAX_BYTES 100

// 排队时暂存的是 UTF-8 原文，UTF-8 一个汉字最多 3 字节，
// 而真正下发前会按 GB2312 的 100 字节再截断一次。
// 取 192（约 1.5 倍以上）是为了保证：即使这里被截断切在汉字中间，
// 那个残缺字符也落在 GB2312 的 100 字节之外，不会被发出去。
#define TTS_TEXT_MAX 192

// ================ 播报时长的估算 ================
// 语音模块不会回传"播完了"的信号，只能按经验时长估算，
// 用来决定下一条什么时候开始播。估长了会有点空档，估短了会打断前一句。
// 中文语音约 4 字/秒，一个汉字 2 字节，故约 125 ms/字节。
#define TTS_BASE_MS 300     // 固定开销
#define TTS_MS_PER_BYTE 125 // 每字节大约念多久

// 等待播报的队列长度，满了就丢等级最低的那条。
// 本次由 3 增到 6：联动上线后事件变多了（风扇自动启停、舵机联动、
// 照明开启都会播报），3 条太容易挤爆。
#define TTS_QUEUE_LEN 6

// ================ 联动播报（本模块的个性化功能） ================
// 1 = 打开：本板额外订阅 report 与 online，自己判断该播什么；
// 0 = 关闭：退回成只订阅 cmd 的普通执行器，平台下发照常工作。
#define TTS_LOCAL_LINKAGE 1

// 联动判定的阈值，现场想调高调低只改这三行
#define TEMP_HIGH 30.0f // 温度达到多少度就播报（协议范围 -40.0~125.0）
#define HUMI_HIGH 80.0f // 湿度达到多少就播报（协议范围 0.0~100.0）
#define LIGHT_LOW 50.0f // 光照低于多少就播报（协议范围 0.0~65535.0）

// 冷却时间：同一条规则在这段时间内不重复播报。
// 火焰会闪、遮挡会抖，没有冷却喇叭会卡在同一句话上反复念。
#define COOLDOWN_ALARM_MS 30000UL // 紧急 / 警告
#define COOLDOWN_INFO_MS 60000UL  // 提示 / 恢复

// ---- 火焰告警的播报节奏（判定逻辑见 linkage.cpp 的 on_evt）----
// 6 号板在火焰持续期间每 5 秒重发一次 detected（防平台漏报），这些重发
// 不是新事件。本板按【轮次】播报：一轮里播开头那一句，之后每 30 秒提醒
// 一次；收到 clear 本轮结束，下次点火立即播报。

// 火焰告警与"已解除"共用的冷却。它只负责挡住火焰抖动造成的
// "检测到 / 已解除"来回刷屏，所以比上面告警的 30 秒短得多。
// 取 3 秒的依据：告警这句本身约 2.2 秒念完，3 秒既不会叠着念，
// 又比演示中"移开火焰再点火"的动作间隔短。设长了就会重演上一版
// "点火时常常不响"的毛病。
#define COOLDOWN_FLAME_MS 3000UL

// 同一轮火焰里"还在烧"的提醒间隔。改成很大的值就只在点火时播一句。
#define FLAME_REMIND_MS 30000UL

// 两条 detected 的间隔超过它，就认为火焰中间断过、开始新的一轮。
// 依据：连续燃烧时这个间隔就是 6 号板的重发周期（5 秒），这里留一倍余量。
// 这条兜底是给 clear 报文丢失用的（6 号板的状态跳变会被它自己的 500ms
// 限流吞掉、发不出来），免得下一次点火被当成重发而不播。
#define FLAME_RESEND_GAP_MS 8000UL

// 舵机动作播报：1 号板转到位后，本板跟着播一句"舵机已转到 X 度"。
// 协议表 8 只给舵机定义了 cmd 与 ack 两类报文，它没有 evt，所以这件事
// 只能从 ack 的 param.angle 里读出来（详见 linkage.cpp 的 on_ack）。
// 改成 0 就不播报舵机动作。
#define TTS_ANNOUNCE_SERVO 1
// 舵机播报的冷却时间。演示时经常连着改几次角度，所以比别的规则短得多；
// 改成 0 就是完全不冷却（每收到一个新角度都播）。
#define COOLDOWN_SERVO_MS 3000UL

// 开机静默期：online 主题是 Retain 的，本板一订阅就会立刻收到
// 所有已在线板的保留报文，不屏蔽的话开机就是一串"X 号设备已上线"。
// 这段时间内只记录不播报。
#define ONLINE_MUTE_MS 20000UL

// 联动动作的播报冷却。扇自动启停、舵机联动这类"执行器自己动起来"
#define COOLDOWN_AUTO_MS 5000UL

// ================ 周期数据汇总播报（本次新增的第三层） ================
// 事件播报与阈值告警都是"出了事才说话"，正常范围内的数据一句都不播，
// 于是听不到系统整体的运行状况。这一层每隔 SUMMARY_PERIOD_MS
// 把各模块的最新值合成一句话念出来。
//
// 关键在于它是【快照】而不是队列：新数据来了只覆盖旧值，不排队。
// 所以无论数据来得多快（八块板合起来每秒两三条报文），
// 念出来的永远是当前值，不会越积越滞后——这也是"逐条播报
// 在物理上不可能"这个矛盾的解法。
#define TTS_SUMMARY_ENABLE 1
#define SUMMARY_PERIOD_MS 30000UL // 多久念一次汇总

// 汇总用的是 TTS_LEVEL_INFO（1 级），是三层里最低的一层：
// 只在空闲时播，不插队、不打断告警。嫌吵就把上面开关改成 0。

// ================ 协议层开关（定义见 mqtt_proto.h） ================
#define ACK_AFTER_DONE 0   // 播报是后台进行的，ack 立即回（协议表 14）
#define SUB_EXTRA_REPORT 1 // 联动旁听：订阅 report
#define SUB_EXTRA_ONLINE 1 // 联动旁听：订阅 online

// ================ MQTT 接收缓冲区 ================
// arduino-mqtt 默认只有 128 字节；本板还要收其他板的 dat / evt 报文，
// 必须显式放大，否则长报文会被截断。
#define MQTT_BUF_SIZE 1024
