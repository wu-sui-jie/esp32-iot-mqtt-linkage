// ==========================================================
//  5 号板 · ADC/RGB/蜂鸣器（rgb、buzzer）
//  文件：rgb.h
//
//  WS2812B 灯带的对外接口：初始化、设置纯色、火焰循环动画控制。
//  实现见 rgb.cpp。
// ==========================================================

#pragma once

#include <Arduino.h>
#include "my_config.h"

#if HAS_RGB

// ============================================================
//  RGB 灯 WS2812B × 4，数据线 GPIO27
//
//  两种工作方式：
//    · 纯色（rgb_apply）—— 平台下发 set_color、光照联动的照明
//    · 火焰循环（rgb_set_fire）—— 火焰联动的多彩报警，按帧刷新
//  火焰循环需要主循环反复调用 rgb_loop() 推进动画，
//  纯色则是一设就保持，不需要循环驱动。
// ============================================================

// 初始化：上电先全灭
void rgb_init();

// 主循环里每次都要调用：推进火焰循环动画（没有动画时立即返回）
void rgb_loop();

// 设置纯色，r / g / b 各 0~255
// 三通道全传 0 即表示熄灭（协议 §5.5：RGB 不单独定义开关命令）
void rgb_apply(uint8_t r, uint8_t g, uint8_t b);

// 开 / 关火焰循环动画。开启时从第一帧开始，
// 关闭时把灯交给调用方（由联动层决定接下来显示什么颜色）
void rgb_set_fire(bool on);

// 火焰循环动画是否在运行
bool rgb_fire_active();

// 当前颜色，用于回执时回发实际状态
uint8_t rgb_get_r();
uint8_t rgb_get_g();
uint8_t rgb_get_b();

#endif
