//  舵机模块的对外接口：初始化、设置目标角度、忙闲与当前位置查询。
//  实现见 servo.cpp。
// ==========================================================

#pragma once

#include <Arduino.h>

// ============================================================
//  1 号板：舵机模块
//
//  角度校验、非阻塞插值状态机、到位判定、LED1 转动指示。
// ============================================================

// 上电初始化：接上舵机、回到中位、配好 LED1
void servo_init();

// 主循环里每次都要调用：每次只走一小步，立刻返回，不阻塞 MQTT
void servo_loop();

// 受理一个目标角度（范围已由 main.cpp 校验过）。
// 返回 true 表示命令被接受。
bool servo_set_angle(int angle);

// 舵机是否还在转动。协议层用它决定 ack 什么时候发出去。
bool servo_busy();

// 当前角度（按步进轨迹推算）
int servo_angle();
